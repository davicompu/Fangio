//! PRISMA 2020 flow diagram as a self-contained SVG. Renders the same lanes
//! as the in-app diagram but in vector form so it can be dropped into a paper.
//!
//! Pure string templating, no external graphics libraries. Embeds Source Sans
//! and a system serif fallback inline so the output is portable.

use crate::db::PrismaState;

const W: i32 = 920;
const PAD: i32 = 32;
const LANE_LABEL_W: i32 = 140;
const BOX_W: i32 = 320;
const BOX_H: i32 = 120;
const GAP: i32 = 60;
const LANE_GAP: i32 = 36;

pub fn render(state: &PrismaState, project_name: &str) -> String {
    let lanes = 3;
    let lane_h = BOX_H + LANE_GAP;
    // The "Records excluded" box grows with the number of exclusion reasons;
    // give the canvas the extra vertical room so it's never clipped.
    let n_reasons = state.by_criterion.iter().filter(|(_, n)| *n > 0).count() as i32;
    let excluded_overflow = ((74 + n_reasons * 16 + 12) - BOX_H).max(0);
    let total_h = PAD * 2 + lane_h * lanes + 80 + excluded_overflow;
    let mut s = String::new();
    s.push_str(&format!(
        r##"<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" width="{W}" height="{total_h}" viewBox="0 0 {W} {total_h}" font-family="Inter, -apple-system, system-ui, sans-serif">
  <style>
    .lane-label {{ font-size: 11px; font-weight: 600; letter-spacing: 0.12em; text-transform: uppercase; fill: #8a8370; }}
    .box {{ fill: #fbfaf7; stroke: #b8b09a; stroke-width: 1.5; }}
    .box-primary {{ fill: #ffffff; stroke: #5e5847; stroke-width: 2; }}
    .box-ink {{ fill: #11182e; stroke: #11182e; }}
    .box-title {{ font-size: 12px; font-weight: 500; fill: #28261f; }}
    .box-title-inv {{ font-size: 12px; font-weight: 500; fill: #ece8dd; }}
    .count {{ font-size: 24px; font-weight: 600; font-family: 'Source Serif 4', Georgia, serif; fill: #1a1814; }}
    .count-large {{ font-size: 36px; font-weight: 600; font-family: 'Source Serif 4', Georgia, serif; fill: #fbfaf7; }}
    .item {{ font-size: 10px; fill: #5e5847; }}
    .arrow {{ stroke: #b8b09a; stroke-width: 1.25; fill: none; }}
    .header {{ font-size: 18px; font-weight: 600; font-family: 'Source Serif 4', Georgia, serif; fill: #1a1814; }}
    .subhead {{ font-size: 11px; fill: #8a8370; }}
  </style>
  <rect width="{W}" height="{total_h}" fill="#fbfaf7"/>
  <text x="{PAD}" y="32" class="header">{project_name}</text>
  <text x="{PAD}" y="50" class="subhead">PRISMA 2020 flow diagram · generated by Reeves</text>
"##
    ));

    let lane_top = |i: i32| 80 + PAD + i * lane_h;
    let label_x = PAD + 4;
    let left_box_x = PAD + LANE_LABEL_W;
    let right_box_x = left_box_x + BOX_W + GAP;

    // Lane 1 — Identification
    let y1 = lane_top(0);
    s.push_str(&lane_label(label_x, y1 + 18, "Identification"));
    s.push_str(&simple_box(
        left_box_x,
        y1,
        BOX_W,
        BOX_H,
        "primary",
        "Records identified from databases",
        Some(state.identified_databases),
        &[],
    ));
    s.push_str(&arrow_h(left_box_x + BOX_W, y1 + BOX_H / 2, right_box_x, y1 + BOX_H / 2));
    s.push_str(&simple_box(
        right_box_x,
        y1,
        BOX_W,
        BOX_H,
        "muted",
        "Records removed before screening",
        None,
        &[
            ("Duplicates removed", state.duplicates_removed),
            ("Marked ineligible by automation", 0),
            ("Other reasons", 0),
        ],
    ));

    // Lane 2 — Screening
    let y2 = lane_top(1);
    s.push_str(&lane_label(label_x, y2 + 18, "Screening"));
    s.push_str(&arrow_v(
        left_box_x + BOX_W / 2,
        y1 + BOX_H,
        left_box_x + BOX_W / 2,
        y2,
    ));
    let sought = state.identified_databases - state.duplicates_removed;
    s.push_str(&simple_box(
        left_box_x,
        y2,
        BOX_W,
        BOX_H,
        "primary",
        "Records screened",
        Some(sought),
        &[],
    ));
    s.push_str(&arrow_h(left_box_x + BOX_W, y2 + BOX_H / 2, right_box_x, y2 + BOX_H / 2));
    let crit_items: Vec<(String, i64)> = state
        .by_criterion
        .iter()
        .filter(|(_, n)| *n > 0)
        .map(|(l, n)| (l.clone(), *n))
        .collect();
    let crit_refs: Vec<(&str, i64)> = crit_items.iter().map(|(l, n)| (l.as_str(), *n)).collect();
    s.push_str(&simple_box(
        right_box_x,
        y2,
        BOX_W,
        BOX_H,
        "muted",
        "Records excluded",
        Some(state.records_excluded),
        &crit_refs,
    ));

    // Lane 3 — Included
    let y3 = lane_top(2);
    s.push_str(&lane_label(label_x, y3 + 18, "Included"));
    s.push_str(&arrow_v(
        left_box_x + BOX_W / 2,
        y2 + BOX_H,
        left_box_x + BOX_W / 2,
        y3,
    ));
    let included_x = left_box_x + (BOX_W + GAP) / 2 - BOX_W / 2;
    s.push_str(&ink_box(
        included_x,
        y3,
        BOX_W,
        BOX_H,
        "Studies included in review",
        state.records_included,
    ));

    s.push_str("</svg>\n");
    s
}

fn lane_label(x: i32, y: i32, label: &str) -> String {
    format!(r##"  <text x="{x}" y="{y}" class="lane-label">{label}</text>"##)
}

fn simple_box(
    x: i32,
    y: i32,
    w: i32,
    h: i32,
    tone: &str,
    title: &str,
    count: Option<i64>,
    items: &[(&str, i64)],
) -> String {
    let class = match tone {
        "primary" => "box box-primary",
        _ => "box",
    };
    // Grow the box so a long reasons list (e.g. many exclusion criteria) stays
    // inside the rounded border instead of spilling past the bottom edge.
    let items_top = if count.is_some() { 74 } else { 48 };
    let h = if items.is_empty() {
        h
    } else {
        h.max(items_top + items.len() as i32 * 16 + 12)
    };
    let mut s = format!(
        r##"
  <g>
    <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" ry="10" class="{class}"/>
    <text x="{tx}" y="{ty}" class="box-title">{title}</text>
"##,
        tx = x + 14,
        ty = y + 22,
        title = escape(title),
    );
    if let Some(n) = count {
        s.push_str(&format!(
            r##"    <text x="{tx}" y="{ty}" class="count">n = {n}</text>
"##,
            tx = x + 14,
            ty = y + 54,
        ));
    }
    // Start the reasons list below the count when one is shown, otherwise just
    // below the title — so boxes without a count (e.g. "Records removed") don't
    // push their last line past the box edge. 16px line height keeps up to four
    // lines inside BOX_H.
    let mut iy = y + items_top;
    for (label, n) in items {
        s.push_str(&format!(
            r##"    <text x="{tx}" y="{iy}" class="item">{label}</text>
    <text x="{nx}" y="{iy}" class="item" text-anchor="end">n = {n}</text>
"##,
            tx = x + 14,
            nx = x + w - 14,
            label = escape(label),
        ));
        iy += 16;
    }
    s.push_str("  </g>\n");
    s
}

fn ink_box(x: i32, y: i32, w: i32, h: i32, title: &str, count: i64) -> String {
    format!(
        r##"
  <g>
    <rect x="{x}" y="{y}" width="{w}" height="{h}" rx="10" ry="10" class="box box-ink"/>
    <text x="{tx}" y="{ty}" class="box-title-inv">{title}</text>
    <text x="{tx}" y="{cy}" class="count-large">n = {count}</text>
  </g>
"##,
        tx = x + 16,
        ty = y + 26,
        cy = y + 70,
        title = escape(title),
    )
}

fn arrow_h(x1: i32, y1: i32, x2: i32, y2: i32) -> String {
    format!(
        r##"  <line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" class="arrow" marker-end="url(#arr)"/>
  <defs><marker id="arr" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto"><path d="M0,0 L10,5 L0,10 z" fill="#b8b09a"/></marker></defs>
"##
    )
}

fn arrow_v(x1: i32, y1: i32, x2: i32, y2: i32) -> String {
    format!(
        r##"  <line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" class="arrow" marker-end="url(#arrv)"/>
  <defs><marker id="arrv" viewBox="0 0 10 10" refX="5" refY="9" markerWidth="6" markerHeight="6" orient="auto"><path d="M0,0 L10,0 L5,10 z" fill="#b8b09a"/></marker></defs>
"##
    )
}

fn escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

pub fn write_to_workspace(
    workspace: &std::path::Path,
    svg: &str,
) -> anyhow::Result<std::path::PathBuf> {
    let dir = workspace.join("prisma");
    std::fs::create_dir_all(&dir)?;
    let path = dir.join("prisma_flow.svg");
    std::fs::write(&path, svg)?;
    Ok(path)
}
