//! CSV exports — protocol-faithful artifacts that match what the original
//! prompt-only system specified.

use crate::db::{ArticleRow, ProjectDb};
use anyhow::Result;
use std::path::{Path, PathBuf};

pub async fn write_all(workspace: &Path, db: &ProjectDb) -> Result<Vec<PathBuf>> {
    let dir = workspace.join("data");
    std::fs::create_dir_all(&dir)?;

    let all = db.list_articles().await?;
    let included = db.list_included_articles_full().await?;
    let excluded = db.list_excluded_articles_full().await?;

    let mut written = Vec::new();
    written.push(write_retrieved(&dir, &all)?);
    written.push(write_included(&dir, &included)?);
    written.push(write_excluded(&dir, &excluded)?);
    written.push(write_bibtex(&dir, &included)?);
    Ok(written)
}

pub fn write_bibtex(dir: &Path, included: &[ArticleRow]) -> Result<PathBuf> {
    let path = dir.join("included.bib");
    let mut s = String::new();
    s.push_str("% Generated by Reeves. Citation keys are stable across exports.\n\n");
    for a in included {
        let key = citation_key(a);
        s.push_str(&format!("@article{{{key},\n"));
        s.push_str(&format!("  title = {{{}}},\n", escape_bib(&a.title)));
        if let Some(authors) = &a.authors {
            // Convert "Smith, J.; Doe, A." to BibTeX " and " separator
            let bib_authors = authors
                .split([';', '\n'])
                .map(|p| p.trim())
                .filter(|p| !p.is_empty())
                .collect::<Vec<_>>()
                .join(" and ");
            s.push_str(&format!("  author = {{{}}},\n", escape_bib(&bib_authors)));
        }
        if let Some(year) = a.year {
            s.push_str(&format!("  year = {{{year}}},\n"));
        }
        if let Some(journal) = &a.journal {
            s.push_str(&format!("  journal = {{{}}},\n", escape_bib(journal)));
        }
        if let Some(doi) = &a.doi {
            s.push_str(&format!("  doi = {{{}}},\n", doi));
        }
        if let Some(url) = &a.url {
            s.push_str(&format!("  url = {{{}}},\n", url));
        }
        if let Some(abstract_text) = &a.abstract_text {
            s.push_str(&format!("  abstract = {{{}}},\n", escape_bib(abstract_text)));
        }
        s.push_str("}\n\n");
    }
    std::fs::write(&path, s)?;
    Ok(path)
}

/// Stable citation key in the form `lastname<year><titleslug>`.
fn citation_key(a: &ArticleRow) -> String {
    let lastname = a
        .authors
        .as_ref()
        .and_then(|s| s.split([';', ',']).next())
        .map(|s| s.trim())
        .unwrap_or("anon")
        .to_lowercase();
    let lastname: String = lastname
        .chars()
        .filter(|c| c.is_ascii_alphabetic())
        .take(20)
        .collect();
    let year = a.year.map(|y| y.to_string()).unwrap_or_else(|| "nd".into());
    let slug: String = a
        .title
        .split_whitespace()
        .filter(|w| w.len() > 3)
        .next()
        .unwrap_or("ref")
        .to_lowercase()
        .chars()
        .filter(|c| c.is_ascii_alphanumeric())
        .take(20)
        .collect();
    format!("{lastname}{year}{slug}")
}

fn escape_bib(s: &str) -> String {
    s.replace('\\', "\\\\")
        .replace('{', "\\{")
        .replace('}', "\\}")
        .replace('%', "\\%")
        .replace('&', "\\&")
        .replace('#', "\\#")
        .replace('$', "\\$")
        .replace('_', "\\_")
        // `^` and `~` are special in LaTeX; the `{}` makes them literal.
        .replace('^', "\\^{}")
        .replace('~', "\\~{}")
}

fn write_retrieved(dir: &Path, articles: &[ArticleRow]) -> Result<PathBuf> {
    let path = dir.join("articles_retrieved.csv");
    let mut wtr = csv::Writer::from_path(&path)?;
    wtr.write_record([
        "ID",
        "Title",
        "Authors",
        "Year",
        "Journal",
        "Abstract",
        "DOI/URL",
        "Search Engine",
        "Status",
    ])?;
    for a in articles {
        wtr.write_record([
            &a.id.to_string(),
            &a.title,
            &a.authors.clone().unwrap_or_default(),
            &a.year.map(|y| y.to_string()).unwrap_or_default(),
            &a.journal.clone().unwrap_or_default(),
            &a.abstract_text.clone().unwrap_or_default(),
            &a.doi.clone().or(a.url.clone()).unwrap_or_default(),
            &a.source_databases.clone().unwrap_or_default(),
            &a.status,
        ])?;
    }
    wtr.flush()?;
    Ok(path)
}

fn write_included(dir: &Path, articles: &[ArticleRow]) -> Result<PathBuf> {
    let path = dir.join("articles_included.csv");
    let mut wtr = csv::Writer::from_path(&path)?;
    wtr.write_record([
        "ID", "Title", "Authors", "Year", "Journal", "Abstract", "DOI/URL", "Search Engine",
    ])?;
    for a in articles {
        wtr.write_record([
            &a.id.to_string(),
            &a.title,
            &a.authors.clone().unwrap_or_default(),
            &a.year.map(|y| y.to_string()).unwrap_or_default(),
            &a.journal.clone().unwrap_or_default(),
            &a.abstract_text.clone().unwrap_or_default(),
            &a.doi.clone().or(a.url.clone()).unwrap_or_default(),
            &a.source_databases.clone().unwrap_or_default(),
        ])?;
    }
    wtr.flush()?;
    Ok(path)
}

fn write_excluded(dir: &Path, articles: &[ArticleRow]) -> Result<PathBuf> {
    let path = dir.join("articles_excluded.csv");
    let mut wtr = csv::Writer::from_path(&path)?;
    wtr.write_record([
        "ID",
        "Title",
        "Authors",
        "Year",
        "Journal",
        "DOI/URL",
        "Exclusion Criterion",
        "Rationale",
    ])?;
    for a in articles {
        wtr.write_record([
            &a.id.to_string(),
            &a.title,
            &a.authors.clone().unwrap_or_default(),
            &a.year.map(|y| y.to_string()).unwrap_or_default(),
            &a.journal.clone().unwrap_or_default(),
            &a.doi.clone().or(a.url.clone()).unwrap_or_default(),
            &a
                .exclusion_criterion
                .map(|n| n.to_string())
                .unwrap_or_default(),
            "", // rationale stored on the row but not selected by list_articles; export raw query later
        ])?;
    }
    wtr.flush()?;
    Ok(path)
}
